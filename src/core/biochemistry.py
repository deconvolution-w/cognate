def get_blosum62_tensor(vocab_list, device="cpu"):
    vocab_size = len(vocab_list)
    matrix = torch.full(
        (vocab_size, vocab_size), -4.0, dtype=torch.float32, device=device
    )

    for row, token_a in enumerate(vocab_list):
        for column, token_b in enumerate(vocab_list):
            if token_a == token_b:
                if token_a in BLOSUM62_RAW:
                    matrix[row, column] = BLOSUM62_RAW[token_a][token_a]
                else:
                    matrix[row, column] = 1.0
            elif token_a in BLOSUM62_RAW and token_b in BLOSUM62_RAW:
                matrix[row, column] = BLOSUM62_RAW[token_a][token_b]

    return matrix
